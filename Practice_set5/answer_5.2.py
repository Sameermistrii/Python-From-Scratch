"""Create a dictionary of three friends and their phone numbers
Use:
keys()  to get all names
values()  to get all numbers
items()  to loop over key-value pairs and print them"""

friends = {
    "Rahul": "9876543210",
    "Aman": "9123456780",
    "Sameer": "9988776655"
}

#keys()  to get all names
print(friends.keys())

#values()  to get all numbers
print(friends.values())

#items()  to loop over key-value
print(friends.items())
