# Convert string to integer
_str = "10"
_int = int(_str)
print(_int) # Output: 10
print(type(_int))

# Convert integer to string
num = 25
num_str = str(num)
print(num_str) # Output: "25"
print(type(num_str))

# Convert float to integer
pi = 3.14
pi_int = int(pi)
print(pi_int) # Output: 3
print(type(pi_int))