# Rule of Defining Variables:
# 1. Variables must start with a letter (a-z, A-Z) or underscore (_)
# 2. They Can only contain letters, numbers, and underscores (A-z, 0-9, and _ )
#  3. Variables are case-sensitive (age, Age, and AGE are three different variables)
# AVoid using Python keywords as variable names (like if, else, while, etc.)

# 34age = 34 # Invalid variable name, cannot start with a number
age = 34 # Valid variable name  
_age = 34 # Valid variable name, starts with an underscore
