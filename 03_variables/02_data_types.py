# python supports several data types :
    # 1. Integer (int): Whole numbers (e.g., 1, 2, 3, -1, -2, -3)
    # 2. Float (float) : Decimal numbers (e.g., 1.0, 2.5, -3.14)
    # 3. String (str) : text data enclosed in quotes (e.g., "Hello", 'World')
    # 4. Boolean (bool): True or False values (e.g., True, False)
    #List (list): Ordered collection of items (e.g., [1, 2, 3], ["apple", "banana"])
    # 5. Tuple (tuple): Ordered, immutable collection of items (e.g., (1, 2, 3), ("apple", "banana"))
    # 6. Set (set): Unordered collection of unique items (e.g., {1, 2, 3}, {"apple", "banana"})
    # 7. Dictionaries (dict): Unordered collection of key-value pairs (e.g., {"name": "John", "age": 30})

age = 3 
print(age)
print(type(age)) 

name = "John"
print(name)
print(type(name))

height = 5.9
print(height)
print(type(height))

is_student = True # can also be False
print(is_student)
print(type(is_student))
